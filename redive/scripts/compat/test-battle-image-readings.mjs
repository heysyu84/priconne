import assert from 'node:assert/strict';
import {selectNicknameReading,reliableOcrNickname,damageFromLabel,selectDamageReading} from '../../public/compat/battle-image-readings.mjs';
const roster=[{id:'a',name:'사이트이름',aliases:['다람이','뿌','1234']},{id:'b',name:'하니',aliases:[]}];
const reads=(...pairs)=>pairs.map(([text,confidence])=>({text,confidence}));
assert.equal(selectNicknameReading(reads(['이상한글자',99],['다람이',35]),roster).memberId,'a');
assert.equal(selectNicknameReading(reads(['뿌',20],['뿌',30]),roster).memberId,'a');
assert.equal(selectNicknameReading(reads(['1234',20],['1234',30]),roster).memberId,'a');
assert.equal(selectNicknameReading(reads(['뿌',0]),roster),null);
assert.equal(selectNicknameReading(reads(['2',99],['2',99]),roster),null);
assert.equal(selectNicknameReading(reads(['다람이',95],['하니',95]),roster),null);
assert.equal(selectNicknameReading(reads(['새로운이름',95]),roster),null);
assert.equal(selectNicknameReading(reads(['새로운이름',70],['새로운이름',60]),roster).text,'새로운이름');
for(const text of ['00000000000','7','10애 02222222222222222222 내0','5...[래','입힌 대미지','11','6".태'])assert.equal(reliableOcrNickname(text),false,text);
for(const [text,n] of [['189633896',189633896],['272,557,284',272557284],['360 074 666',360074666],['42',42]])assert.equal(damageFromLabel(text),n);
for(const text of ['2026/09/28 23:53','0123456789','입힌 189633896','189633896\n152','-12345','000000',''])assert.equal(damageFromLabel(text),null,text);
assert.equal(selectDamageReading(reads(['189633896',80],['189633896',90])).review,false);
assert.equal(selectDamageReading(reads(['189633896',80],['189633898',90])).review,true);
assert.equal(selectDamageReading(reads(['189633896',80])).review,true);
assert.equal(selectDamageReading(reads(['',0])).damage,'');
console.log('PASS: nickname evidence, registered aliases and isolated numeric damage');
