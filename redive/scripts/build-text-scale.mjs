import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const scope='html[data-text-scale]';

// Walk CSS boundaries without treating quoted strings, comments or functions
// as delimiters. The output keeps the source cascade and media queries.
function boundary(text,start,stops){
  let quote='',round=0,square=0;
  for(let i=start;i<text.length;i++){
    const c=text[i];
    if(quote){if(c==='\\')i++;else if(c===quote)quote='';continue;}
    if(c==='/'&&text[i+1]==='*'){const end=text.indexOf('*/',i+2);i=end<0?text.length:end+1;continue;}
    if(c==='"'||c==="'"){quote=c;continue;}
    if(c==='(')round++;else if(c===')')round--;else if(c==='[')square++;else if(c===']')square--;
    if(!round&&!square&&stops.includes(c))return i;
  }
  return text.length;
}
function split(text,separator){
  const result=[];let start=0;
  while(start<text.length){const end=boundary(text,start,[separator]);result.push(text.slice(start,end));start=end+1;}
  return result;
}
function clean(text){return text.replace(/\/\*[\s\S]*?\*\//g,'').trim();}
function closeBlock(text,open){
  let depth=1,start=open+1;
  while(depth&&start<text.length){const next=boundary(text,start,['{','}']);if(next===text.length)throw Error('Unclosed CSS block');depth+=text[next]==='{'?1:-1;start=next+1;}
  return start-1;
}
function scaled(value){
  value=value.replace(/\s*!important\s*$/i,'').trim();
  const absolute=/[\d.](?:px|pt|pc|cm|mm|in|vw|vh|vmin|vmax)\b/i.test(value)||value.includes('var(--base)');
  return absolute?`calc((${value}) * var(--text-scale,1))`:value;
}
function declarations(body,selector){
  const result=[];
  for(const declaration of split(body,';')){
    const colon=boundary(declaration,0,[':']);if(colon===declaration.length)continue;
    const name=clean(declaration.slice(0,colon)).toLowerCase();let value=clean(declaration.slice(colon+1));
    if(name==='font'){
      const size=value.match(/(?:^|\s)(\d*\.?\d+(?:px|pt|pc|cm|mm|in|rem|em|%))(?:\s*\/|\s|$)/i)||value.match(/(var\(--base\))/);
      if(size)result.push(`font-size:${scaled(size[1],selector)}!important`);
      else if(/^(inherit|initial|unset|revert)(?:\s*!important)?$/i.test(value))result.push(`font-size:${scaled(value,selector)}!important`);
    }else if(name==='font-size'||name==='--battle-log-font-size')result.push(`${name}:${scaled(value,selector,name)}!important`);
  }
  return result.join(';');
}
function scopedSelector(selector){
  selector=clean(selector);
  // Fixed-size checkbox marks and decorative pseudo elements are not text.
  if(!selector||/::?(?:before|after)\b/.test(selector))return '';
  return /^(?:html|:root)\b/.test(selector)?selector.replace(/^(?:html|:root)/,scope):`${scope} ${selector}`;
}
export function scaleStyles(css){
  const result=[];let start=0;
  while(start<css.length){
    const open=boundary(css,start,['{',';']);if(open===css.length)break;
    if(css[open]===';'){start=open+1;continue;}
    const head=clean(css.slice(start,open)),end=closeBlock(css,open),body=css.slice(open+1,end);start=end+1;
    if(/^@(media|supports|container|layer)\b/i.test(head)){
      const nested=scaleStyles(body);if(nested)result.push(`${head}{\n${nested}\n}`);
    }else if(!head.startsWith('@')){
      // Separate selector groups because navigation, tactic content and ordinary
      // text intentionally use different mobile scales and desktop minimums.
      const groups=new Map();
      for(const selector of split(head,',')){
        const scoped=scopedSelector(selector),rules=declarations(body,clean(selector));
        if(scoped&&rules){if(!groups.has(rules))groups.set(rules,[]);groups.get(rules).push(scoped);}
      }
      for(const [rules,selectors] of groups)result.push(`${selectors.join(',\n')}{${rules}}`);
    }
  }
  return result.join('\n');
}
export function buildTextScale(root=fileURLToPath(new URL('..',import.meta.url))){
  const publicDir=path.join(root,'public'),head=fs.readFileSync(path.join(publicDir,'index.html'),'utf8').split('</head>')[0];
  const files=[...head.matchAll(/<link rel="stylesheet" href="\.\/([^"?#]+)(?:\?[^"#]*)?"/g)].map(m=>m[1]).filter(n=>n!=='text-scale.css');
  const output='html[data-text-scale]{font-size:calc(16px * var(--text-scale,1))}\n/* Generated by scripts/build-text-scale.mjs. Font sizes only; layout dimensions stay unchanged. */\n'+files.map(name=>`/* ${name} */\n${scaleStyles(fs.readFileSync(path.join(publicDir,name),'utf8'))}`).join('\n')+'\n';
  const safariInputFix="\n/* iOS Safari: focused form fields must compute to at least 16px, even when text scale is 90%. */\n@media(max-width:760px){\n  html[data-text-scale] body input:not([type=checkbox]):not([type=radio]):not([type=file]):not([type=hidden]),\n  html[data-text-scale] body select,\n  html[data-text-scale] body textarea,\n  html[data-text-scale] body input:not([type=checkbox]):not([type=radio]):not([type=file]):not([type=hidden]):focus,\n  html[data-text-scale] body select:focus,\n  html[data-text-scale] body textarea:focus{font-size:max(16px,calc(14px * var(--text-scale,1)))!important}\n}\n";
  const tableTypographyFix="\n\n/* Shared table typography follows the historical expanded battle-log design. */\nhtml[data-text-scale] .data-table thead th,\nhtml[data-text-scale] .data-table.battle-table.expanded thead th{\n  font-size:calc(11px * var(--text-scale,1))!important;\n}\nhtml[data-text-scale] .data-table tbody td,\nhtml[data-text-scale] .data-table.battle-table.expanded tbody td{\n  font-size:calc(13px * var(--text-scale,1))!important;\n}\n@media(max-width:760px){\n  html[data-text-scale] .data-table.battle-mobile-table thead th{\n    font-size:calc(11px * var(--text-scale,1))!important;\n  }\n  html[data-text-scale] .data-table.battle-mobile-table tbody td{\n    font-size:clamp(calc(11px * var(--text-scale,1)),calc(3.2vw * var(--text-scale,1)),calc(13px * var(--text-scale,1)))!important;\n  }\n}\n";
  fs.writeFileSync(path.join(publicDir,'text-scale.css'),output+safariInputFix+tableTypographyFix);
  return output+safariInputFix+tableTypographyFix;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(`Text scale styles: ${buildTextScale().length} characters`);
