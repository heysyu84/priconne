import assert from 'node:assert/strict';
import {CARRY_GROUP,GROUPS,groupOf,carryTacticsVisible,tacticGroupsFor} from '../public/tactics-model.mjs';
import {createTacticWorkspace} from '../public/tactics-workspace.mjs';

assert.deepEqual(GROUPS,['택틱정리','타비비토','이월 택틱']);
assert.equal(groupOf({source:CARRY_GROUP}),CARRY_GROUP);
assert.equal(carryTacticsVisible({options:{}}),true);
assert.deepEqual(tacticGroupsFor({options:{showCarryTactics:false}}),['택틱정리','타비비토']);

const listeners=new Map();
globalThis.document={activeElement:null,querySelector:()=>null,querySelectorAll:()=>[],addEventListener:(type,callback)=>{const callbacks=listeners.get(type)||[];callbacks.push(callback);listeners.set(type,callbacks);}};
globalThis.localStorage={getItem:()=>null,setItem:()=>{},removeItem:()=>{}};
const app={active:'2026-10',months:{'2026-10':{month:'2026-10',options:{battleSeconds:90,carryMaxSeconds:90},bosses:[{id:1,name:'테스트 보스'}],tactics:[],communityLinks:[{id:'carry-link',label:'이월 모음',url:'https://example.com/carry'}]},'2026-11':{month:'2026-11',options:{battleSeconds:90,carryMaxSeconds:90,showCarryTactics:false},bosses:[{id:1,name:'다음 달 보스'}],tactics:[],communityLinks:[]}}};
let editable=true,saves=0,unlocks=0;
const workspace=createTacticWorkspace({getApp:()=>app,getMonth:()=>app.months[app.active],canEdit:()=>editable,persist:()=>saves++,render:()=>{},notify:()=>{},navigate:()=>{},section:(title,description,actions)=>`<h1>${title}</h1>${description}${actions}`,copyText:()=>{},unlock:()=>unlocks++,catalog:[],bossStatus:()=>[]});
const click=(action,value)=>{const button={dataset:{tw:action,value}};const event={target:{closest:selector=>selector==='[data-tw]'?button:null},preventDefault:()=>{}};for(const listener of listeners.get('click')||[])listener(event);};
const tabs=html=>[...html.match(/class="tw-group-tabs"[\s\S]*?<\/div>/)[0].matchAll(/data-value="([^"]+)"/g)].map(match=>match[1]);
assert.deepEqual(tabs(workspace.view()),['택틱정리','타비비토','이월 택틱','외부 택틱']);
click('group',CARRY_GROUP);
assert.match(workspace.view(),/등록된 이월 택틱이 없습니다/);
click('new');
const month=app.months[app.active],carry=month.tactics[0];
assert.equal(carry.group,CARRY_GROUP);
assert.equal(carry.source,CARRY_GROUP);
assert.deepEqual(carry.rows,[],'new collection has no sample content');
assert.equal(saves,1);
let html=workspace.view();
for(const field of ['tw-boss','tw-char-0','tw-manual','tw-tp','tw-expected','tw-note','tw-video','tw-rows'])assert.ok(html.includes(`id="${field}"`),field);
assert.ok(html.includes('SET 포함 복사'));
carry.rows.push({id:'carry-row',text:'0:20 전체 SET',checked:[true,false,false,false,false,false]});
const preserved=JSON.stringify(carry);
month.options.showCarryTactics=false;
html=workspace.view();
assert.deepEqual(tabs(html),['택틱정리','타비비토','외부 택틱']);
assert.match(html,/data-value="택틱정리"/);
assert.equal(JSON.stringify(carry),preserved,'hiding only changes navigation');
assert.ok(html.includes('이월 모음'),'community link stays independent');
assert.ok(!html.includes('0:20 전체 SET'),'hidden carry content is absent from the normal editor');
month.options.showCarryTactics=true;
click('group',CARRY_GROUP);
assert.ok(workspace.view().includes('0:20'));
assert.equal(JSON.stringify(carry),preserved);
editable=false;
html=workspace.view();
assert.ok(html.includes('disabled'));
assert.ok(!html.includes('data-tw="new"'));
click('new');
assert.equal(month.tactics.length,1);
assert.equal(unlocks,1);
assert.equal(saves,1,'viewing and hiding do not save or edit tactics');
app.active='2026-11';
assert.deepEqual(tabs(workspace.view()),['택틱정리','타비비토','외부 택틱']);
assert.equal(app.months['2026-10'].options.showCarryTactics,true,'month settings are independent');
const restored=JSON.parse(JSON.stringify(app));
assert.equal(carryTacticsVisible(restored.months['2026-11']),false);
assert.equal(restored.months['2026-10'].tactics[0].rows[0].text,'0:20 전체 SET');
console.log('Carry tactics: tab order, editor, empty creation, permissions, hide/show preservation, month switching and serialization passed.');
