// Exercise the browser-local draft and copy flow without any shared-data API.
const storage = new Map(), elements = new Map();
for (const id of ['#tw-external-source', '#tw-external-result', '#tw-external-status', '#tw-external-note', '#tw-carry', '[data-tw="external-copy"]', '[data-tw="original"]']) {
  elements.set(id, {value:'',textContent:'',dataset:{},disabled:false,hidden:false,setAttribute(name,value){this[name]=value;}});
}
globalThis.document = {querySelector: selector => elements.get(selector)};
globalThis.localStorage = {getItem: key => storage.get(key) ?? null, setItem: (key,value) => storage.set(key,value)};
const copies = [], notices = [];
const options = {baseSeconds:()=>90, escapeHtml:String, copyText:text=>copies.push(text), notify:text=>notices.push(text)};
let tool = createExternalTacticCarry(options);
tool.mount();
assert.equal(elements.get('[data-tw="external-copy"]').disabled, true);
tool.input({id:'tw-external-source',value:source});
assert.equal(tool.apply('65'), true);
assert.equal(elements.get('#tw-carry').value, '1:05');
assert.equal(elements.get('#tw-external-result').value, expected);
tool.copy();
assert.deepEqual(copies, [expected]);
tool = createExternalTacticCarry(options);
tool.mount();
assert.equal(elements.get('#tw-external-source').value, source, 'draft survives recreation');
assert.equal(elements.get('#tw-external-result').value, expected);
tool.input({id:'tw-carry',value:'1:99'});
assert.equal(elements.get('[data-tw="external-copy"]').disabled, true);
tool.copy();
assert.equal(copies.length, 1, 'invalid time cannot copy a stale result');
tool.reset();
assert.equal(elements.get('#tw-external-result').value, source, 'reset keeps the original text');
assert.equal(elements.get('[data-tw="original"]').disabled, true);
tool.input({id:'tw-external-base',value:'1:10'});
assert.equal(elements.get('[data-tw="original"]').title, '원본 1:10로 초기화');
tool.reset();
assert.equal(elements.get('#tw-carry').value, '1:10');
assert.equal(tool.input({id:'some-other-input',value:'ignored'}), false);
console.log('External tactic carry: inline times, parentheses, ranges, second references, durations, URLs, exact text, draft restore and copy passed.');
