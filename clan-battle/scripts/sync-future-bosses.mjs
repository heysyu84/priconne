/**
 * Refresh read-only Korean future clan-battle previews from Aikurumi JP data.
 * Aikurumi gvg_front: GET /api/pcr/clanBattleList?server=jp,
 *                     POST /api/pcr/gvgTask {server,clanBattleId,stage}.
 * Never touches the editable month in Cloudflare D1.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

const root=path.resolve(fileURLToPath(new URL('../../',import.meta.url)));
const sourceBase='https://aikurumi.cn/api';
const offsetMonths=13;
const monthKey=/^\d{4}-(0[1-9]|1[0-2])$/;
const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const rootFile=name=>path.join(root,name);

export function addMonths(month,delta){
  if(!monthKey.test(month))throw Error('Invalid month: '+month);
  const [y,m]=month.split('-').map(Number);
  const num=y*12+m-1+delta;
  return Math.floor(num/12)+'-'+String(num%12+1).padStart(2,'0');
}
export function parseStartMonth(value){
  const s=String(value??'');
  const iso=s.match(/^(\d{4})[-/](\d{1,2})/);
  if(iso)return iso[1]+'-'+iso[2].padStart(2,'0');
  const time=Number(value);
  if(Number.isFinite(time)&&time>1e9){
    const date=new Date(time<1e12?time*1000:time);
    if(!Number.isNaN(date.getTime()))return new Intl.DateTimeFormat('en-CA',{year:'numeric',month:'2-digit',timeZone:'Asia/Tokyo'}).format(date).replace('/','-');
  }
  return null;
}
export function getCurrentKrMonth(now=new Date()){
  const parts=new Intl.DateTimeFormat('en-US',{year:'numeric',month:'2-digit',timeZone:'Asia/Seoul'}).formatToParts(now);
  const get=type=>parts.find(x=>x.type===type)?.value;
  return get('year')+'-'+get('month');
}
function signedHeaders(){
  // Same anonymous, ephemeral request signature generated by upstream gvg_front.
  const d=String(Date.now()),l=Math.random()*d.length;
  const t=createHash('sha1').update(d.substr(l)+'123456').digest('hex');
  return {d,l:String(l),t,'Accept':'application/json','Content-Type':'application/json','User-Agent':'NyangClanBossPreview/1.0'};
}
async function request(api,{method='GET',body=null}={}){
  let lastError;
  for(let attempt=0;attempt<2;attempt++){
    try{
      const response=await fetch(sourceBase+api,{
        method,headers:signedHeaders(),body:body===null?undefined:JSON.stringify(body),
        signal:AbortSignal.timeout(20000),
      });
      if(!response.ok)throw Error('HTTP '+response.status);
      const json=await response.json();
      if(json.code!==200||!('data' in json))throw Error('Unexpected Aikurumi response '+String(json.code));
      return json.data;
    }catch(error){lastError=error;if(attempt===0)await pause(1500);}
  }
  throw Error(api+': '+lastError.message);
}
function fiveBosses(raw){
  if(!Array.isArray(raw))throw Error('Boss list is not an array');
  const bosses=[...raw].sort((a,b)=>Number(a.index??0)-Number(b.index??0)).slice(0,5);
  if(bosses.length!==5||bosses.some(x=>!Number.isInteger(Number(x.prefabId))||Number(x.prefabId)<=0||!String(x.unitName||'').trim()))
    throw Error('Incomplete boss lineup');
  if(new Set(bosses.map(x=>String(x.prefabId))).size!==5)throw Error('Duplicate boss prefab IDs');
  return bosses.map((b,i)=>({slot:i+1,prefabId:Number(b.prefabId),sourceName:String(b.unitName).trim()}));
}
function normalize(s){return String(s||'').normalize('NFKC').replace(/[\s·・･()（）\-ー_]/g,'').toLowerCase();}
export function buildPreview(current,cycles,catalog,previous={}){
  const historical=new Map(),conflicting=new Set();
  // Prefer prefab IDs grounded by observed JP lineup + verified Korean month, never
  // guess boss identity from position across different months.
  for(const cycle of cycles){
    const existing=catalog[addMonths(cycle.jpMonth,offsetMonths)];
    if(!existing||!cycle.bosses)continue;
    for(const b of cycle.bosses){
      const known=existing[String(b.slot)];
      if(!known?.name||known.mappingStatus==='unmatched')continue;
      const key=String(b.prefabId);
      const record={name:known.name,referenceKey:known.referenceKey||null,portrait:known.portrait||null};
      if(historical.has(key)&&historical.get(key).name!==record.name)conflicting.add(key);
      else historical.set(key,record);
    }
  }
  for(const id of conflicting)historical.delete(id);
  const names=new Map();
  for(const [name,record] of Object.entries(catalog.catalog||{})){
    for(const alias of [name,record.japaneseName,...(record.aliases||[])]){
      if(alias)names.set(normalize(alias),{name,referenceKey:record.referenceKey||null,portrait:record.portrait||null});
    }
  }
  for(const entries of Object.values(catalog)){
    if(!entries?.['1'])continue;
    for(const entry of Object.values(entries)){
      if(!entry?.name)continue;
      for(const alias of [entry.name,entry.japaneseName]){
        if(alias)names.set(normalize(alias),{name:entry.name,referenceKey:entry.referenceKey||null,portrait:entry.portrait||null});
      }
    }
  }
  const months={...previous.months};
  for(const cycle of cycles){
    const kr=addMonths(cycle.jpMonth,offsetMonths);
    if(kr<current||!cycle.bosses)continue;
    const bosses=cycle.bosses.map(b=>{
      const known=historical.get(String(b.prefabId))||names.get(normalize(b.sourceName));
      return {
        slot:b.slot,prefabId:b.prefabId,sourceName:b.sourceName,
        name:known?.name||b.sourceName,
        referenceKey:known?.referenceKey||null,
        portrait:known?.portrait||null,
        status:known?'verified':'unmatched'
      };
    });
    months[kr]={jpMonth:cycle.jpMonth,krMonth:kr,clanBattleId:cycle.id,bosses};
  }
  // Keep previously checked months when the source is temporarily incomplete.
  return {source:'aikurumi.cn (JP)',offsetMonths,months:Object.fromEntries(Object.entries(months).sort(([a],[b])=>a.localeCompare(b)))};
}
async function main(){
  const catalog=JSON.parse(await fs.readFile(rootFile('docs/bosses.json'),'utf8'));
  const outputPaths=[rootFile('docs/future-bosses.json'),rootFile('clan-battle/public/future-bosses.json')];
  let previous={source:'aikurumi.cn (JP)',offsetMonths,months:{}};
  try{previous=JSON.parse(await fs.readFile(outputPaths[0],'utf8'));}catch{}
  const now=getCurrentKrMonth(),latest=addMonths(now,offsetMonths);
  const list=await request('/pcr/clanBattleList?server=jp');
  if(!Array.isArray(list))throw Error('No Japanese clan-battle periods');
  const byMonth=new Map();
  for(const item of list){
    const month=parseStartMonth(item.startTime),id=Number(item.clanBattleId);
    if(!monthKey.test(month||'')||!Number.isSafeInteger(id)||id<=0)continue;
    const kr=addMonths(month,offsetMonths);
    if(kr>latest||kr<'2026-01')continue;
    if(!byMonth.has(month))byMonth.set(month,{jpMonth:month,id});
  }
  // Fetch history to learn stable prefabId -> Korean name mappings; fetch
  // upcoming cycles independently. No historical raid records are modified.
  const cycles=[];
  for(const cycle of [...byMonth.values()].sort((a,b)=>a.jpMonth.localeCompare(b.jpMonth))){
    try{
      cycle.bosses=fiveBosses(await request('/pcr/gvgTask',{method:'POST',body:{stage:4,server:'jp',clanBattleId:cycle.id}}));
      cycles.push(cycle);
    }catch(error){console.warn('Skipped',cycle.jpMonth,error.message);}
    await pause(350);
  }
  if(!cycles.some(c=>addMonths(c.jpMonth,offsetMonths)>=now))
    throw Error('No valid future JP lineup returned. Existing previews left unchanged.');
  const next=buildPreview(now,cycles,catalog,previous);
  const currentComparable=JSON.stringify({source:previous.source,offsetMonths:previous.offsetMonths,months:previous.months||{}});
  if(JSON.stringify(next)===currentComparable){console.log('Future boss lineups unchanged');return;}
  const document=JSON.stringify({...next,updatedAt:new Date().toISOString()},null,2)+'\n';
  for(const output of outputPaths)await fs.writeFile(output,document);
  console.log('Updated',Object.keys(next.months).length,'month previews; next',now);
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  main().catch(e=>{console.error('Future boss sync failed:',e.message);process.exitCode=1;});
}
